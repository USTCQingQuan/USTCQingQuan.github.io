await writeFile(FILE, JSON.stringify(doc, null, 2) + '\n', 'utf8');

const dist = {};
for (const r of doc.resources) for (const t of r.tags) dist[t] = (dist[t] || 0) + 1;
const thin = doc.resources.filter((r) => r.tags.length <= 1);

