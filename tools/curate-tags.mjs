// 校验：策展表与数据必须一一对应，不允许静默漏项
const titles = new Set(doc.resources.map((r) => r.title));
const missing = doc.resources.filter((r) => !CURATED[r.title]).map((r) => r.title);
const extra = Object.keys(CURATED).filter((t) => !titles.has(t));
if (missing.length) { console.error('策展表缺少以下条目（拒绝静默跳过）:\n  ' + missing.join('\n  ')); process.exit(1); }
if (extra.length) { console.error('策展表存在数据中不存在的条目:\n  ' + extra.join('\n  ')); process.exit(1); }

let changed = 0;
const before = [];
for (const r of doc.resources) {
  const old = JSON.stringify(r.tags || []);
  const neu = JSON.stringify(CURATED[r.title]);
  if (old !== neu) { changed++; before.push([r.title, old, neu]); }
  r.tags = CURATED[r.title];
}

// 顺带修掉唯一一条 language_support 未判定的条目
const uc = doc.resources.find((r) => r.title === 'USTC-Course');
